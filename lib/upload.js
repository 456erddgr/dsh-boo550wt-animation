/**
 * dsh-boo550wt-animation — custom upload storage.
 *
 * Users can upload their own video / image / html for the boot animation from
 * the Settings panel. Uploads land in a dedicated directory next to the
 * settings file, with a `.meta.json` ledger (title + sha256) so identical
 * re-uploads return the existing entry instead of piling up copies.
 *
 * Disciplines (borrowed from dsh-plugin-wallpaper-engine):
 *   - Stream to a `.tmp` file while hashing; rename is the atomic publish.
 *   - Backpressure: pause the request when the write buffer fills.
 *   - On client abort / error / timeout, destroy the stream and clean the
 *     `.tmp` — never leave an open handle or a partial file behind.
 *   - The meta ledger is written atomically and read through a non-throwing
 *     reader; a broken or missing ledger degrades to {}.
 */

import { createHash } from "node:crypto";
import {
  createWriteStream,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { extname, join } from "node:path";

export const UPLOAD_MAX_BYTES = 512 * 1024 * 1024;
const CONTROL_MAX_BYTES = 1024 * 1024;
const BODY_IDLE_MS = 60_000;

/** MIME type -> extension for the kinds the boot animation accepts. */
const UPLOAD_EXT = {
  "image/png": "png",
  "image/jpeg": "jpg",
  "image/jpg": "jpg",
  "image/gif": "gif",
  "image/webp": "webp",
  "video/mp4": "mp4",
  "video/webm": "webm",
  "text/html": "html",
  "application/xhtml+xml": "html",
};

/** Map a stored extension to the boot mode it can drive. */
export function uploadKind(ext) {
  if (ext === "mp4" || ext === "webm") return "video";
  if (ext === "html") return "web";
  return "image";
}

/** Directory holding uploaded assets; created on demand. */
export function uploadDir() {
  const base = process.env.DSH_HOME?.trim() || process.cwd();
  const dir = join(base, "boot-animation-uploads");
  mkdirSync(dir, { recursive: true });
  return dir;
}

function metaPath() {
  return join(uploadDir(), ".meta.json");
}

/** Read the ledger; missing / broken / non-object degrades to {}. */
export function readMeta() {
  const p = metaPath();
  if (!existsSync(p)) return {};
  try {
    const o = JSON.parse(readFileSync(p, "utf8"));
    return o && typeof o === "object" && !Array.isArray(o) ? o : {};
  } catch {
    return {};
  }
}

/** Publish the ledger atomically. */
function writeMeta(meta) {
  const p = metaPath();
  const tmp = `${p}.tmp${process.pid}`;
  writeFileSync(tmp, JSON.stringify(meta, null, 2), "utf8");
  renameSync(tmp, p);
}

/**
 * Resolve one stored file name to its absolute path.
 * The id is a bare file name generated by this module; the prefix and the
 * containment check keep path traversal impossible.
 */
export function resolveUpload(name) {
  if (typeof name !== "string" || !/^up-[A-Za-z0-9.-]+$/.test(name)) return null;
  const dir = uploadDir();
  const full = join(dir, name);
  if (!full.startsWith(dir) || !existsSync(full)) return null;
  return full;
}

/** List every stored asset with its ledger entry. */
export function listUploads() {
  const dir = uploadDir();
  const meta = readMeta();
  const out = [];
  let names = [];
  try {
    names = readdirSync(dir);
  } catch {
    return out;
  }
  for (const name of names) {
    if (!name.startsWith("up-") || name.endsWith(".tmp")) continue;
    const entry = meta[name] && typeof meta[name] === "object" ? meta[name] : {};
    const ext = extname(name).slice(1).toLowerCase();
    out.push({
      name,
      title: typeof entry.title === "string" && entry.title.trim() ? entry.title : name,
      sha256: typeof entry.sha256 === "string" ? entry.sha256 : null,
      bytes: typeof entry.bytes === "number" ? entry.bytes : null,
      kind: uploadKind(ext),
      url: `/boot-animation/uploads/${encodeURIComponent(name)}`,
    });
  }
  out.sort((a, b) => (a.title < b.title ? -1 : a.title > b.title ? 1 : 0));
  return out;
}

function json(res, status, body) {
  const payload = JSON.stringify(body);
  res.statusCode = status;
  res.setHeader("Content-Type", "application/json; charset=utf-8");
  res.setHeader("Cache-Control", "no-store");
  res.end(payload);
}

/**
 * Handle POST /upload: stream the raw body to a `.tmp` file, hash it,
 * deduplicate by sha256, then publish with a ledger entry.
 */
export function handleUpload(req, res) {
  const method = (req.method || "GET").toUpperCase();
  if (method !== "POST") {
    res.statusCode = 405;
    res.end("method not allowed");
    return;
  }
  const query = new URL(req.url || "/", "http://x").searchParams;
  const title = (query.get("title") || "").trim().slice(0, 80);
  const ctype = String(req.headers["content-type"] || "").split(";")[0].trim().toLowerCase();
  const ext = UPLOAD_EXT[ctype];
  if (!ext) {
    json(res, 415, {
      error: `不支持的格式：${ctype || "(空)"}（仅支持 PNG / JPG / GIF / WEBP / MP4 / WEBM / HTML）`,
    });
    return;
  }

  const dir = uploadDir();
  const name = `up-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}.${ext}`;
  const fileAbs = join(dir, name);
  const tmpAbs = `${fileAbs}.tmp`;
  const hash = createHash("sha256");
  const ws = createWriteStream(tmpAbs);
  let size = 0;
  let failed = false;
  let completed = false;
  let idle = null;

  const cleanupTmp = () => {
    try { unlinkSync(tmpAbs); } catch { /* ignore */ }
  };
  const fail = (code, payload) => {
    if (failed) return;
    failed = true;
    if (idle !== null) clearTimeout(idle);
    try { ws.destroy(); } catch { /* ignore */ }
    json(res, code, payload);
  };

  ws.on("error", () => fail(500, { error: "upload write failed" }));
  ws.on("close", () => { if (failed) cleanupTmp(); });
  // A client that disappears mid-upload never reaches 'end': clean up here.
  req.once("close", () => {
    if (completed || failed) return;
    failed = true;
    if (idle !== null) clearTimeout(idle);
    try { ws.destroy(); } catch { /* ignore */ }
    cleanupTmp();
  });

  const armIdle = () => {
    if (idle !== null) clearTimeout(idle);
    idle = setTimeout(() => fail(408, { error: "request timeout" }), BODY_IDLE_MS);
  };
  armIdle();

  req.on("data", (chunk) => {
    if (failed) return;
    armIdle();
    size += chunk.length;
    if (size > UPLOAD_MAX_BYTES) {
      fail(413, { error: "文件过大（上限 512MB）" });
      return;
    }
    hash.update(chunk);
    // Backpressure: a full write buffer pauses the request until 'drain'.
    if (!ws.write(chunk)) req.pause();
  });
  ws.on("drain", () => { if (!failed) req.resume(); });

  req.on("end", () => {
    if (idle !== null) clearTimeout(idle);
    if (failed) return;
    completed = true;
    ws.end(() => {
      try {
        const sha = hash.digest("hex");
        const meta = readMeta();
        // Content dedup: the same bytes must not become a second entry.
        for (const known of Object.keys(meta)) {
          const entry = meta[known] && typeof meta[known] === "object" ? meta[known] : {};
          if (entry.sha256 !== sha) continue;
          const existing = resolveUpload(known);
          if (existing === null) continue;
          failed = true; // so ws 'close' removes the fresh .tmp
          json(res, 200, {
            name: known,
            title: typeof entry.title === "string" && entry.title.trim() ? entry.title : known,
            kind: uploadKind(extname(existing).slice(1).toLowerCase()),
            duplicate: true,
            url: `/boot-animation/uploads/${encodeURIComponent(known)}`,
          });
          return;
        }
        renameSync(tmpAbs, fileAbs);
        meta[name] = { title: title || name, sha256: sha, bytes: size };
        writeMeta(meta);
        json(res, 200, {
          name,
          title: title || name,
          kind: uploadKind(ext),
          bytes: size,
          url: `/boot-animation/uploads/${encodeURIComponent(name)}`,
        });
      } catch (err) {
        failed = true;
        json(res, 500, { error: String(err && err.message ? err.message : err) });
      }
    });
  });
  req.on("error", () => fail(400, { error: "request error" }));
}

/** Handle POST /upload-remove: delete one stored asset by name. */
export function handleRemove(req, res) {
  const method = (req.method || "GET").toUpperCase();
  if (method !== "POST") {
    res.statusCode = 405;
    res.end("method not allowed");
    return;
  }
  const chunks = [];
  let size = 0;
  let tooLarge = false;
  req.on("data", (chunk) => {
    size += chunk.length;
    if (size > CONTROL_MAX_BYTES) {
      tooLarge = true;
      req.destroy();
      return;
    }
    chunks.push(chunk);
  });
  req.on("end", () => {
    if (tooLarge) return;
    let body;
    try {
      body = JSON.parse(Buffer.concat(chunks).toString("utf8") || "{}");
    } catch {
      json(res, 400, { error: "invalid JSON" });
      return;
    }
    const name = body?.name;
    if (typeof name !== "string") {
      json(res, 400, { error: "missing name" });
      return;
    }
    const file = resolveUpload(name);
    if (file === null) {
      json(res, 404, { error: "not found" });
      return;
    }
    try {
      unlinkSync(file);
      const meta = readMeta();
      delete meta[name];
      writeMeta(meta);
      json(res, 200, { ok: true, name });
    } catch (err) {
      json(res, 500, { error: String(err && err.message ? err.message : err) });
    }
  });
  req.on("error", () => json(res, 400, { error: "request error" }));
}
